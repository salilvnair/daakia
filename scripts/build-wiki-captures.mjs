#!/usr/bin/env node
/**
 * Compiles plan/daakia_live/<protocol>/{manifest.json,*.html} into a single
 * TS module per protocol (webview-ui/src/pages/wiki/daakia-view/<protocol>/captures.ts)
 * exporting an array of { id, label, explanation, html }, consumed by
 * CaptureScrollView. Re-run this after adding/recapturing screens.
 *
 * Usage: node scripts/build-wiki-captures.mjs [protocol ...]  (defaults to all)
 */
import { readFileSync, writeFileSync, existsSync, readdirSync, mkdirSync } from 'fs';
import { join } from 'path';
import { fileURLToPath } from 'url';

const ROOT = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const LIVE_DIR = join(ROOT, 'plan', 'daakia_live');
const OUT_ROOT = join(ROOT, 'webview-ui', 'src', 'pages', 'wiki', 'daakia-view');

function buildProtocol(protocol) {
  const dir = join(LIVE_DIR, protocol);
  const manifestPath = join(dir, 'manifest.json');
  if (!existsSync(manifestPath)) {
    console.log(`skip ${protocol}: no manifest.json`);
    return;
  }
  const manifest = JSON.parse(readFileSync(manifestPath, 'utf-8'));
  const entries = manifest.map(m => {
    const html = readFileSync(join(dir, m.file), 'utf-8');
    return { id: m.id, label: m.label, explanation: m.explanation, html };
  });

  const outDir = join(OUT_ROOT, protocol);
  mkdirSync(outDir, { recursive: true });
  const outFile = join(outDir, 'captures.ts');

  const body = entries.map(e => `  {
    id: ${JSON.stringify(e.id)},
    label: ${JSON.stringify(e.label)},
    explanation: ${JSON.stringify(e.explanation)},
    html: ${JSON.stringify(e.html)},
  },`).join('\n');

  const content = `/**
 * AUTO-GENERATED by scripts/build-wiki-captures.mjs from plan/daakia_live/${protocol}/.
 * Do not hand-edit — re-run the script after adding/recapturing screens.
 */
import type { CaptureEntry } from '../capture/CaptureScrollView';

export const ${protocol.toUpperCase().replace(/-/g, '_')}_CAPTURES: CaptureEntry[] = [
${body}
];
`;
  writeFileSync(outFile, content, 'utf-8');
  console.log(`wrote ${outFile} (${entries.length} screens, ${(content.length / 1024).toFixed(1)}KB)`);
}

const args = process.argv.slice(2);
const protocols = args.length > 0 ? args : readdirSync(LIVE_DIR).filter(d => existsSync(join(LIVE_DIR, d, 'manifest.json')));
for (const p of protocols) buildProtocol(p);
